using System.Collections.Concurrent;
using System.Text.RegularExpressions;

namespace MinecraftServerManager.UnitTests.Architecture;
/// <summary>架構規則違反記錄項目</summary>
public sealed record SourceViolation(
    string FilePath,
    int LineNumber,
    string LineContent,
    string RuleId,
    string Message);

/// <summary>原始碼文字掃描、註解/字串清洗與架構違規偵測之共用工具</summary>
public static class SourceScanner
{
    private static readonly Lazy<string> SolutionRootLazy = new(ResolveSolutionRoot);

    /// <summary>取得專案儲存庫根目錄絕對路徑</summary>
    public static string SolutionRoot => SolutionRootLazy.Value;

    private static string ResolveSolutionRoot()
    {
        string? current = AppContext.BaseDirectory;
        while (!string.IsNullOrEmpty(current))
        {
            if (File.Exists(Path.Combine(current, "MinecraftServerManager.slnx")) ||
                File.Exists(Path.Combine(current, "Directory.Build.props")))
            {
                return Path.GetFullPath(current);
            }

            DirectoryInfo? parent = Directory.GetParent(current);
            if (parent is null)
            {
                break;
            }

            current = parent.FullName;
        }

        throw new InvalidOperationException($"無法自路徑 '{AppContext.BaseDirectory}' 向上定位專案儲存庫根目錄。");
    }

    private static readonly ConcurrentDictionary<(string Directory, string Pattern), IReadOnlyList<(string RelativePath, string FullPath)>> SourceFilesCache = new();

    /// <summary>取得目錄下符合樣式的原始碼（預設 C#；排除專案層 bin、obj 與檔頭標示 auto-generated 的 .g.cs）</summary>
    public static IReadOnlyList<(string RelativePath, string FullPath)> GetSourceFiles(string relativeDirectory, string searchPattern = "*.cs") =>
        SourceFilesCache.GetOrAdd((relativeDirectory, searchPattern), static key =>
        {
            string fullDirectory = Path.Combine(SolutionRoot, key.Directory);
            if (!Directory.Exists(fullDirectory))
            {
                return [];
            }

            var results = new List<(string RelativePath, string FullPath)>();
            EnumerateFilesPruned(fullDirectory, key.Pattern, results);
            return results;
        });

    private static void EnumerateFilesPruned(string directory, string pattern, List<(string RelativePath, string FullPath)> results)
    {
        foreach (string file in Directory.EnumerateFiles(directory, pattern))
        {
            if (file.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) && HasAutoGeneratedHeader(file))
            {
                continue;
            }

            string relativePath = Path.GetRelativePath(SolutionRoot, file).Replace('\\', '/');
            results.Add((relativePath, file));
        }

        foreach (string subDir in Directory.EnumerateDirectories(directory))
        {
            string dirName = Path.GetFileName(subDir);
            if (dirName.Equals("bin", StringComparison.OrdinalIgnoreCase) ||
                dirName.Equals("obj", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            EnumerateFilesPruned(subDir, pattern, results);
        }
    }

    /// <summary>檔頭前五行含 &lt;auto-generated 標記即視為產生碼</summary>
    private static bool HasAutoGeneratedHeader(string file) =>
        File.ReadLines(file).Take(5).Any(static line => line.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));

    /// <summary>清除單行/多行註解與字串字面值為等長空格（保留插值字串內運算式與換行對齊）</summary>
    public static string StripCommentsAndStrings(string sourceCode) => StripCore(sourceCode, commentRanges: null);

    /// <summary>僅清除註解為等長空格（保留字串字面值與換行對齊）</summary>
    public static string StripCommentsOnly(string sourceCode)
    {
        if (string.IsNullOrEmpty(sourceCode))
        {
            return string.Empty;
        }

        var commentRanges = new List<(int Start, int End)>();
        _ = StripCore(sourceCode, commentRanges);

        char[] chars = sourceCode.ToCharArray();
        foreach (var (start, end) in commentRanges)
        {
            for (int k = start; k < end; k++)
            {
                if (chars[k] is not '\r' and not '\n')
                {
                    chars[k] = ' ';
                }
            }
        }

        return new string(chars);
    }

    private static string StripCore(string sourceCode, List<(int Start, int End)>? commentRanges)
    {
        if (string.IsNullOrEmpty(sourceCode))
        {
            return string.Empty;
        }

        char[] chars = sourceCode.ToCharArray();
        StripCode(chars, 0, stopAtCloseBrace: false, commentRanges);
        return new string(chars);
    }

    /// <summary>掃描程式碼並清除註解與字串；<paramref name="stopAtCloseBrace"/> 為 true 時於同層 '}' 停止並回傳其位置（插值洞）</summary>
    private static int StripCode(char[] chars, int i, bool stopAtCloseBrace, List<(int Start, int End)>? commentRanges)
    {
        int len = chars.Length;
        int depth = 0;
        while (i < len)
        {
            int start = i;
            char c = chars[i];
            char next = i + 1 < len ? chars[i + 1] : '\0';

            if (stopAtCloseBrace && c == '{')
            {
                depth++;
            }
            else if (stopAtCloseBrace && c == '}' && depth-- == 0)
            {
                return i;
            }

            // 註解：單行 // 止於換行，多行 /* */ 止於 */（未結束則至檔尾）
            if (c == '/' && next is '/' or '*')
            {
                int end = IndexOf(chars, next == '/' ? "\n" : "*/", next == '/' ? i : i + 2);
                end = end >= 0 && next == '*' ? end + 2 : end;
                i = end < 0 ? len : end;
                Blank(chars, start, i);
                commentRanges?.Add((start, i));
                continue;
            }

            // 字元字面值
            if (c == '\'')
            {
                i = SkipQuoted(chars, i + 1, '\'', verbatim: false, interpolated: false, commentRanges);
                Blank(chars, start, start + 1);
                continue;
            }

            // 字串：前綴為任意數量 $ 與至多一個 @，另含原始字串（三個以上引號）
            int quote = i;
            while (quote < len && chars[quote] is '$' or '@')
            {
                quote++;
            }

            if (quote >= len || chars[quote] != '"' || (quote > i && i > 0 && IsIdentifierChar(chars[i - 1])))
            {
                i++;
                continue;
            }

            ReadOnlySpan<char> prefix = chars.AsSpan(i, quote - i);
            bool verbatim = prefix.Contains('@');
            int dollars = prefix.Count('$');
            int quoteRun = CountRun(chars, quote);
            if (!verbatim && quoteRun >= 3)
            {
                Blank(chars, start, quote + quoteRun);
                i = SkipRawString(chars, quote + quoteRun, quoteRun, dollars, commentRanges);
                continue;
            }

            Blank(chars, start, quote + 1);
            i = SkipQuoted(chars, quote + 1, '"', verbatim, interpolated: dollars > 0, commentRanges);
        }

        return i;
    }

    /// <summary>清除原始字串內容至結尾引號；插值洞（連續 $ 個數之大括號）內的程式碼保留並遞迴清洗</summary>
    private static int SkipRawString(char[] chars, int i, int quoteRun, int dollars, List<(int Start, int End)>? commentRanges)
    {
        int len = chars.Length;
        while (i < len)
        {
            if (chars[i] == '"')
            {
                int run = CountRun(chars, i);
                Blank(chars, i, i + run);
                i += run;
                if (run >= quoteRun)
                {
                    return i;
                }

                continue;
            }

            if (dollars > 0 && chars[i] == '{' && CountRun(chars, i) >= dollars)
            {
                int run = CountRun(chars, i);
                Blank(chars, i, i + run);
                i = StripCode(chars, i + run, stopAtCloseBrace: true, commentRanges);
                int close = Math.Min(CountRun(chars, i), dollars);
                Blank(chars, i, i + close);
                i += close;
                continue;
            }

            Blank(chars, i, i + 1);
            i++;
        }

        return i;
    }

    private static bool IsIdentifierChar(char c) => char.IsLetterOrDigit(c) || c == '_';

    private static int IndexOf(char[] chars, string value, int start)
    {
        int index = chars.AsSpan(start).IndexOf(value.AsSpan(), StringComparison.Ordinal);
        return index < 0 ? -1 : start + index;
    }

    /// <summary>清除 XAML 註解 &lt;!-- --&gt; 為等長空格（屬性值與 URL 保留）</summary>
    public static string StripXamlComments(string xaml)
    {
        if (string.IsNullOrEmpty(xaml))
        {
            return string.Empty;
        }

        char[] chars = xaml.ToCharArray();
        for (int start = IndexOf(chars, "<!--", 0); start >= 0; start = IndexOf(chars, "<!--", start))
        {
            int end = IndexOf(chars, "-->", start + 4);
            end = end < 0 ? chars.Length : end + 3;
            Blank(chars, start, end);
            start = end;
            if (start >= chars.Length)
            {
                break;
            }
        }

        return new string(chars);
    }

    /// <summary>將範圍內除換行外的字元改為空白</summary>
    private static void Blank(char[] chars, int start, int end)
    {
        for (int k = start; k < end; k++)
        {
            if (chars[k] is not '\r' and not '\n')
            {
                chars[k] = ' ';
            }
        }
    }

    private static int CountRun(char[] chars, int index)
    {
        int count = 0;
        while (index + count < chars.Length && chars[index + count] == chars[index])
        {
            count++;
        }

        return count;
    }

    /// <summary>清除自開頭引號之後至結尾引號（含）的內容，回傳其後位置；插值運算式 {…} 保留程式碼並遞迴清洗</summary>
    private static int SkipQuoted(char[] chars, int i, char quote, bool verbatim, bool interpolated, List<(int Start, int End)>? commentRanges)
    {
        int len = chars.Length;
        while (i < len)
        {
            char c = chars[i];
            bool doubled = i + 1 < len && chars[i + 1] == c;
            if (!verbatim && c == '\\' && i + 1 < len)
            {
                Blank(chars, i, i + 2);
                i += 2;
            }
            else if (c == quote && verbatim && doubled)
            {
                Blank(chars, i, i + 2);
                i += 2;
            }
            else if (c == quote)
            {
                chars[i] = ' ';
                return i + 1;
            }
            else if (interpolated && c == '{' && doubled)
            {
                Blank(chars, i, i + 2);
                i += 2;
            }
            else if (interpolated && c == '{')
            {
                chars[i] = ' ';
                i = StripCode(chars, i + 1, stopAtCloseBrace: true, commentRanges);
                if (i < len)
                {
                    chars[i++] = ' ';
                }
            }
            else
            {
                Blank(chars, i, i + 1);
                i++;
            }
        }

        return i;
    }

    private sealed record CleanedFile(
        string[] OriginalLines,
        string StrippedWithoutStrings,
        string[] StrippedWithoutStringsLines,
        string StrippedPreservingStrings,
        string[] StrippedPreservingStringsLines);

    private static readonly ConcurrentDictionary<string, CleanedFile> FileCache = new(StringComparer.OrdinalIgnoreCase);

    private static CleanedFile GetCleanedFile(string fullPath) =>
        FileCache.GetOrAdd(fullPath, static path =>
        {
            string rawText = File.ReadAllText(path);
            string[] originalLines = rawText.Split('\n');

            if (path.EndsWith(".xaml", StringComparison.OrdinalIgnoreCase))
            {
                string strippedXaml = StripXamlComments(rawText);
                string[] xamlLines = strippedXaml.Split('\n');
                return new CleanedFile(originalLines, strippedXaml, xamlLines, strippedXaml, xamlLines);
            }

            var commentRanges = new List<(int Start, int End)>();
            char[] charsWithoutStrings = rawText.ToCharArray();
            StripCode(charsWithoutStrings, 0, stopAtCloseBrace: false, commentRanges);
            string strippedWithoutStrings = new(charsWithoutStrings);
            string[] strippedWithoutStringsLines = strippedWithoutStrings.Split('\n');

            char[] charsPreservingStrings = rawText.ToCharArray();
            foreach (var (start, end) in commentRanges)
            {
                Blank(charsPreservingStrings, start, end);
            }
            string strippedPreservingStrings = new(charsPreservingStrings);
            string[] strippedPreservingStringsLines = strippedPreservingStrings.Split('\n');

            return new CleanedFile(
                originalLines,
                strippedWithoutStrings,
                strippedWithoutStringsLines,
                strippedPreservingStrings,
                strippedPreservingStringsLines);
        });

    /// <summary>依副檔名清洗：XAML 僅剝除 XML 註解；C# 剝除註解（必要時連同字串）</summary>
    public static string Clean(string path, string rawText, bool preserveStrings) =>
        path.EndsWith(".xaml", StringComparison.OrdinalIgnoreCase) ? StripXamlComments(rawText)
        : preserveStrings ? StripCommentsOnly(rawText)
        : StripCommentsAndStrings(rawText);

    /// <summary>以正規表示式掃描違規；<paramref name="multiline"/> 為 true 時對全文比對（可跨行）並回報起始行</summary>
    public static List<SourceViolation> ScanViolations(
        IEnumerable<(string RelativePath, string FullPath)> files,
        Regex pattern,
        string ruleId,
        string ruleDescription,
        Func<string, bool> isWhitelisted,
        bool preserveStrings = false,
        bool multiline = false)
    {
        var violations = new List<SourceViolation>();

        foreach (var (relativePath, fullPath) in files)
        {
            if (isWhitelisted(relativePath))
            {
                continue;
            }

            CleanedFile file = GetCleanedFile(fullPath);
            string stripped = preserveStrings ? file.StrippedPreservingStrings : file.StrippedWithoutStrings;
            string[] strippedLines = preserveStrings ? file.StrippedPreservingStringsLines : file.StrippedWithoutStringsLines;

            IEnumerable<int> hitLines = multiline
                ? pattern.Matches(stripped).Select(m => stripped.AsSpan(0, m.Index).Count('\n')).Distinct()
                : Enumerable.Range(0, strippedLines.Length).Where(idx => pattern.IsMatch(strippedLines[idx]));

            foreach (int lineIdx in hitLines)
            {
                string rawLine = lineIdx < file.OriginalLines.Length ? file.OriginalLines[lineIdx].TrimEnd('\r') : string.Empty;
                violations.Add(new SourceViolation(relativePath, lineIdx + 1, rawLine.Trim(), ruleId, ruleDescription));
            }
        }

        return violations;
    }
}
